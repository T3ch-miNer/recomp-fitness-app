import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {getYouData,setYouHabit,addYouHabit,removeYouHabit,habitStreak,todayHabitStats,validateDeviceDay,clearDeviceDays,rememberDeviceDay,renderYouPage} from '../you-page.js';
const data=new Map();
globalThis.localStorage={getItem:k=>data.has(k)?data.get(k):null,setItem:(k,v)=>data.set(k,String(v)),removeItem:k=>data.delete(k)};
const reset=()=>data.clear();
test('You tracks user-created habits and handles missed days without fabricated streaks',()=>{
 reset();
 const d='2026-10-27';
 const initial=getYouData();
 assert.equal(initial.habits.length,3);
 assert.equal(todayHabitStats(initial,d).completed,0);
 for(const habit of initial.habits)setYouHabit(habit.id,'2026-10-26',true);
 assert.equal(habitStreak(getYouData(),d),1,'yesterday remains a valid streak while today is incomplete');
 setYouHabit(initial.habits[0].id,d,true);
 assert.equal(habitStreak(getYouData(),d),1);
 for(const habit of initial.habits.slice(1))setYouHabit(habit.id,d,true);
 assert.equal(habitStreak(getYouData(),d),2);
 addYouHabit('Read 10 pages');
 assert.equal(todayHabitStats(getYouData(),d).all,false,'a new unchecked habit changes the daily goal');
 const id=getYouData().habits.at(-1).id;
 removeYouHabit(id);
 assert.equal(getYouData().habits.length,3);
});
test('only bounded daily totals are accepted from Android and users can erase them',()=>{
 reset();
 const date='2026-10-27';
 assert.throws(()=>validateDeviceDay({date,screenMinutes:-2,unlocks:0},date),/Invalid/);
 assert.throws(()=>validateDeviceDay({date,screenMinutes:4,unlocks:1.5},date),/Invalid/);
 assert.throws(()=>validateDeviceDay({date:'2026-10-26',screenMinutes:4,unlocks:1},date),/Unexpected date/);
 rememberDeviceDay({date,screenMinutes:71.8,unlocks:12});
 assert.equal(getYouData().device[date].screenMinutes,72);
 clearDeviceDays();
 assert.equal(Object.keys(getYouData().device).length,0);
});
test('browser You dashboard never claims to read Android statistics',()=>{
 reset();
 const html=renderYouPage({date:'2026-10-27',activity:{steps:4800},stepGoal:8000,dailyTasksDone:1,dailyTasksTotal:3});
 assert.match(html,/You\./);
 assert.match(html,/4,800/);
 assert.match(html,/manual|browser|Android APK/i);
 assert.doesNotMatch(html,/data-action="you-usage-settings"/);
 const app=readFileSync(new URL('../app.js',import.meta.url),'utf8');
 assert.match(app,/you:youView/);
 assert.match(app,/\['you','user','You'\]/);
 assert.match(app,/case 'you-sync-steps'/);
 const sw=readFileSync(new URL('../sw.js',import.meta.url),'utf8');
 assert.match(sw,/recipe-variations\.js/);
 assert.match(sw,/you-page\.js/);
});

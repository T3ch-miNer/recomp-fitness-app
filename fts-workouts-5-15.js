export function mergeFtsWorkoutExpansion(existing) {
  const current=Array.isArray(existing)?existing:[];
  const all=[...FTS_WORKOUTS,...FTS_WORKOUTS_5_TO_15];
  const previous=new Map(current.filter(t=>t&&t.id).map(t=>[t.id,t]));
  return [
    ...all.map(plan=>previous.get(plan.id)||structuredClone(plan)),
    ...current.filter(plan=>!all.some(imported=>imported.id===plan?.id))
  ];
}

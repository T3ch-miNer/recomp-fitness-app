export function mergeFtsWorkouts(existing) {
  const current = Array.isArray(existing) ? existing : [];
  const byId = new Map(current.map(plan => [plan?.id, plan]));
  return [
    ...FTS_WORKOUTS.map(plan => byId.get(plan.id) || structuredClone(plan)),
    ...current.filter(plan => !FTS_WORKOUTS.some(imported => imported.id === plan?.id))
  ];
}
